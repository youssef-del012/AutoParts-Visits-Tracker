const dict: Record<Lang, Dict> = { en, ar };

export type TFunc = (key: string, params?: Record<string, string | number>) => string;

interface AdminLangContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFunc;
  isRTL: boolean;
}

const AdminLangContext = createContext<AdminLangContextValue | undefined>(undefined);

function readStoredLang(): Lang {
  try {
    const saved = localStorage.getItem("admin_lang");
    if (saved === "en" || saved === "ar") return saved;
  } catch {
    /* ignore */
  }
  return "en";
}

export function AdminLangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("admin_lang", l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback<TFunc>(
    (key, params) => {
      let s = dict[lang][key] ?? dict.en[key] ?? key;
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        }
      }
      return s;
    },
    [lang]
  );

  const value = useMemo(
    () => ({ lang, setLang, t, isRTL: lang === "ar" }),
    [lang, setLang, t]
  );

  return <AdminLangContext.Provider value={value}>{children}</AdminLangContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLang(): AdminLangContextValue {
  const ctx = useContext(AdminLangContext);
  if (!ctx) throw new Error("useLang must be used inside <AdminLangProvider>");
  return ctx;
}
